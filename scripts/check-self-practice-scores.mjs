import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source=await fs.readFile('src/services/selfPractice/scores.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText.replace(/import .*?from .*?;\n/g,'');
const {selfPracticePoints}=await import('data:text/javascript;base64,'+Buffer.from('const roundPoints=v=>Math.round((v+Number.EPSILON)*100)/100;\n'+js).toString('base64'));
const work=(quizId,earnedPoints,maxPoints=10,extra={})=>({classId:'c',studentId:'s',quizId,kind:'QUIZ',subject:'Toán',result:{earnedPoints,maxPoints},...extra});
const total=works=>selfPracticePoints(works,'c','s');
assert.equal(total([work('q',8)]),8);
assert.equal(total([work('q',8),work('q',8),work('q',6)]),8);
assert.equal(total([work('q',8),work('q',9)]),9);
assert.equal(total([work('q',8),work('other',7)]),15);
assert.equal(total([work('q',4,5)]),8);
assert.equal(total([work('q',1,3)]),3.33);
assert.equal(total([work('q',8,10,{studentId:'other'}),work('q',8,10,{classId:'other'}),work('q',8,10,{kind:'WRITING'})]),0);
for(const points of [NaN,Infinity,-1,11])assert.equal(total([work('q',points)]),0);
assert.equal(total([work('q',0,0)]),0);
assert.equal(selfPracticePoints([work('q',8)],'c','s','Tiếng Việt'),0);
assert.equal(total([work('pending',3,10,{result:{earnedPoints:3,maxPoints:10,pendingReview:true,pendingPoints:7}})]),0);
console.log('PASS: ten-point conversion, highest attempt, retries, class/student/subject isolation, writing and invalid results excluded.');
